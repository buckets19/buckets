// Builds server/sim.js from the game itself (../index.html), so the server always runs the exact
// same rules, physics and bots as the iPads. Run before every deploy:  node build.mjs
import fs from 'node:fs';
const html = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const cut = (a, b) => { const i = html.indexOf(a), j = html.indexOf(b); if (i < 0 || j < 0 || j < i) throw new Error('marker missing: ' + a); return html.slice(i, j); };
const sim = cut('// @@SIM-BEGIN', '// @@SIM-END');
const riv = cut('// @@RIV-BEGIN', '// @@RIV-END');
const dif = cut('// @@DIFF-BEGIN', '// @@DIFF-END');
// single-line helpers defined elsewhere in the game that the simulation also uses
const line = name => {
  const m = html.split('\n').find(l => l.startsWith('const ' + name + ' ') || l.startsWith('function ' + name + '('));
  if (!m) throw new Error('helper missing: ' + name); return m;
};
const helpers = ['pick'].map(line).join('\n');
const out = `// AUTO-GENERATED by build.mjs from index.html. Do not edit by hand.
export function makeSim(){
  "use strict";
  const handleEvent = () => {};          // sounds/effects only happen on the iPads
${helpers}
${sim}
${riv}
${dif}
  return { HALF_D, newMatch, stepMatch, makeSnap, findP, looseBall, BOTDIFF, RIVALS, RIVAL_BY, rivalRR, diffForRR, BOT_NAMES, MAX_PER_TEAM, hash, cleanName, Q };
}
`;
fs.writeFileSync(new URL('./sim.js', import.meta.url), out);
console.log('sim.js built:', out.length, 'bytes');
