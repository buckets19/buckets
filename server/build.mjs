// Builds server/sim.js from the game itself (../index.html), so the server always runs the exact
// same rules, physics and bots as the iPads. Run before every deploy:  node build.mjs
import fs from 'node:fs';
const html = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const cut = (a, b) => { const i = html.indexOf(a), j = html.indexOf(b); if (i < 0 || j < 0 || j < i) throw new Error('marker missing: ' + a); return html.slice(i, j); };
const sim = cut('// @@SIM-BEGIN', '// @@SIM-END');
const riv = cut('// @@RIV-BEGIN', '// @@RIV-END');
const dif = cut('// @@DIFF-BEGIN', '// @@DIFF-END');
// single-line helpers defined elsewhere in the game that the simulation also uses
const line = name => {
  const m = html.split('\n').find(l => l.startsWith('const ' + name + ' ') || l.startsWith('function ' + name + '('));
  if (!m) throw new Error('helper missing: ' + name); return m;
};
const helpers = ['pick'].map(line).join('\n');
const out = `// AUTO-GENERATED by build.mjs from index.html. Do not edit by hand.
export function makeSim(){
  "use strict";
  const handleEvent = () => {};          // sounds/effects only happen on the iPads
${helpers}
${sim}
${riv}
${dif}
  return { METER_T, SWEET, HALF_D, newMatch, stepMatch, makeSnap, findP, looseBall, BOTDIFF, RIVALS, RIVAL_BY, rivalRR, diffForRR, BOT_NAMES, MAX_PER_TEAM, hash, cleanName, Q };
}
`;
fs.writeFileSync(new URL('./sim.js', import.meta.url), out);
console.log('sim.js built:', out.length, 'bytes');

// ---- 🛒 catalog.js: every item, pack, price and reward table, read straight from the game, so the server's
// wallet always prices and rolls exactly what the iPads show (new items need no extra work: just rebuild).
{
  const grab = name => {   // "const NAME=" ... up to its matching close bracket
    const i = html.indexOf('const ' + name + '='); if (i < 0) throw new Error('catalog: missing ' + name);
    let k = html.indexOf('=', i) + 1; while (html[k] === ' ') k++; const open = html[k], close = open === '[' ? ']' : '}'; let d = 0, q = null;
    for (let j = k; j < html.length; j++) { const c = html[j];
      if (q) { if (c === String.fromCharCode(92)) { j++; continue; } if (c === q) q = null; continue; }
      if (c === "'" || c === '"' || c === '`') { q = c; continue; }
      if (c === open) d++; else if (c === close && --d === 0) return html.slice(i, j + 1) + ';'; }
    throw new Error('catalog: unbalanced ' + name); };
  const src = [
    line('SKINS'), cut('const RAR={', 'const SAVE_KEY='), cut("const SHOES=['#f8f8ff'", 'function hslHex('),
    'function cosOpt(pi,oi){ return LOOK_PARTS[pi].opts[oi]; } function cosPrice(o){ return (o && COS_PRICE[o.r])||0; } function cosFind(k,n){ const pi=LOOK_PARTS.findIndex(P=>P.k===k); return [pi, LOOK_PARTS[pi].opts.findIndex(o=>o.n===n)]; }',
    cut('const STYLE_SETS=[', '// ---- daily rotation'),
    ...['FEATS', 'LOGIN_REW', 'PASS_REW', 'QUEST_POOL', 'SEASON_COINS', 'SEASON_ITEMS', 'TIERS', 'CODE_HASHES', 'GEM_FOR'].map(grab),
    html.split('\n').find(l => l.startsWith('const QUEST_BONUS=')).split(';')[0] + ';', html.split('\n').find(l => l.startsWith('const PASS_XP=')),
    'return {RAR,RORDER,KINDS,PACKS,XMAS_PACK,SPECIAL_PACKS,SETS,FEAT_SETS,SET_MILES,LOOK_PARTS,COS_PRICE,STYLE_SETS,FEATS,LOGIN_REW,PASS_REW,PASS_XP,PASS_MAX,QUEST_POOL,QUEST_BONUS,SEASON_COINS,SEASON_ITEMS,TIERS,CODE_HASHES,GEM_FOR};'].join('\n');
  const C = new Function('console', 'document', 'window', 'localStorage', 'location', 'navigator', src)({ log() {}, warn() {} }, {}, {}, { getItem() { return null; } }, { hostname: '' }, {});
  const cat = {
    rar: Object.fromEntries(Object.entries(C.RAR).map(([k, v]) => [k, { refund: v.refund || 0 }])), rorder: C.RORDER,
    kinds: Object.fromEntries(Object.entries(C.KINDS).map(([k, K]) => [k, { def: K.def, list: K.list.map(i => ({ id: i.id, r: i.r, s: i.s || '', nc: i.noCrate ? 1 : 0 })) }])),
    packs: [...C.PACKS, C.XMAS_PACK, ...C.SPECIAL_PACKS].map(p => ({ id: p.id, price: p.price || 0, gems: p.gems || 0, cards: p.cards, guar: p.guar || '', odds: p.odds, set: p.set || '', freeOnly: !!p.freeOnly })),
    sets: Object.keys(C.SETS), featSets: C.FEAT_SETS, setMiles: C.SET_MILES.map(m => ({ p: m.p, pack: m.rw.pack || '' })),
    cos: C.LOOK_PARTS.map(P => ({ k: P.k, r: P.opts.map(o => o.r || 'free') })), cosPrice: C.COS_PRICE,
    styleSets: C.STYLE_SETS.map(S => ({ n: S.n, list: S.list })),
    feats: C.FEATS.map(f => ({ id: f.id, goal: f.goal, kind: f.kind, item: f.item })), login: C.LOGIN_REW, passRew: C.PASS_REW, passXP: C.PASS_XP, passMax: C.PASS_MAX,
    questMax: Math.max(...C.QUEST_POOL.map(q => q.r)), questBonus: C.QUEST_BONUS, seasonCoins: C.SEASON_COINS, seasonItems: C.SEASON_ITEMS,
    tiers: C.TIERS.map(t => t.min), codes: C.CODE_HASHES, gemFor: C.GEM_FOR,
  };
  const cs = '// AUTO-GENERATED by build.mjs from index.html. Do not edit by hand.\nexport default ' + JSON.stringify(cat) + ';\n';
  fs.writeFileSync(new URL('./catalog.js', import.meta.url), cs);
  console.log('catalog.js built:', cs.length, 'bytes,', Object.values(cat.kinds).reduce((t, k) => t + k.list.length, 0), 'items,', cat.cos.reduce((t, p) => t + p.r.length, 0), 'style options');
}
